/// 标量代数系统。
///
/// # 概述
///
/// `ScalarAlgebra` 抽象一个**标量域上的交换代数**（commutative algebra over a scalar field）。
/// 一个类型 `S: ScalarAlgebra` 同时具备：
///
/// - 加法群结构：`zero` / `add` / `neg`
/// - 交换幺半环结构：`one` / `mul`（逐分量乘）
/// - 标量模结构：`scale: Scalar × S → S`
/// - 上述结构间的相容性（分配律、双线性、标量嵌入为环同态）
///
/// 它建模的是「一组标量按某个基逐分量组织起来的量」，而不是某个具体物理量。
/// `f32`（单通道）、`Rgb`（三通道）都是它的实例，且共用同一套泛型代码。
///
/// **类型层面允许负值与非归一化值**。物理有效性（非负、能量守恒、
/// 色域边界等）不属于本 trait 的职责，由上层保证。
///
/// # 代数结构分类
///
/// 记 `S` 为 `Self`，`K` 为 `Self::Scalar`。本 trait 要求：
///
/// | 结构 | 记号 | 对应方法 | 是否强制 |
/// |---|---|---|---|
/// | 加法交换群 | `(S, +, 0, neg)` | `zero` `add` `neg` | 签名强制，公理靠文档 |
/// | 乘法交换幺半群 | `(S, ·, 1)` | `one` `mul` | 签名强制，公理靠文档 |
/// | 乘法对加法双线性 | `·` 对 `+` 分配 | `add` `mul` | 文档约定 |
/// | `K`-模 | `K × S → S` | `scale` | 签名强制 |
/// | `K`-代数 | 模 + 环 + 相容 | 全部 | 文档约定 |
///
/// 因此 `(S, +, ·, 0, 1, neg)` 构成**交换环**，再叠加 `K`-模结构，`S` 是
/// **`K` 上的交换代数**。这里 `K` 期望是域（实际为 `f32`，是近似域）。
///
/// **它不是**：
///
/// - **半环 / 半模**：因为有 `neg`，`scale` 接受任意 `K`，封闭于负值。
/// - **锥（cone）**：同上，没有非负约束。
/// - **域**：当通道数 `I ≥ 2` 时存在零因子（如 `[1,0,0] · [0,1,0] = 0`），
///   故仅为交换环，非整环，非域。仅 `I = 1`（如 `f32`）时退化为域。
/// - **内积空间 / 赋范空间**：本 trait 不涉及配对、范数、拓扑。
///   `max_abs` 只是工程辅助，不构成范数公理。
///
/// # 公理
///
/// 实现者必须保证以下等式对所有 `a, b, c: S`、`k, l: K` 成立。
/// Rust 无法在类型层面强制这些公理，违反者语义错误，行为未定义（逻辑意义）。
///
/// **加法群**
///
/// ```text
/// a.add(&b).add(&c)   == a.add(&b.add(&c))    // 结合
/// a.add(&b)           == b.add(&a)            // 交换
/// a.add(&S::zero())   == a                    // 单位元
/// a.add(&a.neg())     == S::zero()            // 逆元
/// ```
///
/// **乘法幺半群**
///
/// ```text
/// a.mul(&b).mul(&c)   == a.mul(&b.mul(&c))    // 结合
/// a.mul(&b)           == b.mul(&a)            // 交换
/// a.mul(&S::one())    == a                    // 单位元
/// ```
///
/// **分配律 / 双线性**
///
/// ```text
/// a.mul(&b.add(&c))   == a.mul(&b).add(&a.mul(&c))        // 对加法分配
/// a.scale(k).add(&b.scale(k)) == a.add(&b).scale(k)       // 标量加性
/// a.scale(k + l)      == a.scale(k).add(&a.scale(l))      // 标量加性（另一侧）
/// a.scale(k).mul(&b)  == a.mul(&b).scale(k)               // 标量交换
/// a.scale(k * l)      == a.scale(k).scale(l)              // 标量结合
/// a.scale(K::one())   == a                                // 标量单位
/// ```
///
/// 注意最后三条一起蕴含 `mul` 对 `scale` 双线性，这是 `K`-代数的核心相容条件。
///
/// **标量嵌入**
///
/// 定义 `embed(k) = S::one().scale(k)`（即物理上的「常数谱 `k`」）。要求
/// `embed: K → S` 是环同态：
///
/// ```text
/// embed(0) == S::zero()
/// embed(1) == S::one()
/// embed(k + l) == embed(k).add(&embed(l))
/// embed(k * l) == embed(k).mul(&embed(l))
/// ```
///
/// 在 `mul` 结合且含 `one` 的前提下，后两条由 `scale` 的相容性自动成立。
///
/// # `mul` 的语义：点式代数
///
/// `mul` 是**相对于某个基的逐分量（Hadamard）乘**，不是内积，不是卷积，
/// 不是复合。形式化地：存在通道索引集 `I`，使 `S ≅ K^I`（直积环），
/// 对 `a = Σ_i a_i e_i`、`b = Σ_i b_i e_i` 有
///
/// ```text
/// a.mul(&b) = Σ_i (a_i * b_i) e_i
/// ```
///
/// - `f32`：`I = {0}`，`mul` 即标量乘，与 `scale` 重合。
/// - `Rgb`：`I = {R, G, B}`，`mul` 是逐通道乘。
///
/// 这一语义使 `S` 成为 `K^I` 的**逐点代数（pointwise algebra）/ 函数代数**，
/// 这也是「整体标量」与「分量通道」两种解读共享同一结构的原因：
/// 单通道只是 `|I| = 1` 的特例。
///
/// 实现者若选择了非逐分量的双线性乘（如光谱积分、基变换后的乘），
/// 依然满足本 trait 的公理，但「逐分量」这一物理直觉不再成立，
/// 需在自身文档中说明。
///
/// # 为什么存在 `neg`
///
/// 物理量（能量、辐亮度、透射率）非负，但**代数运算**需要负值：
/// 差分、残差、梯度、球谐系数、控制变量、误差图、迭代求解中间量。
/// 若只提供 `scale` 而不提供 `neg`，`neg` 仍可被 `scale(-1)` 隐式构造，
/// 类型系统既未获得「非负」保证，又失去了显式接口。因此本 trait 选择
/// **显式承认负元**：类型层面封闭于负值，物理有效性由上层检查。
///
/// 如果确有「必须非负」的场景，应当在外层用 newtype 包装并限制构造子，
/// 而不是削弱本 trait 的代数结构。
///
/// # 零因子与不可逆性
///
/// `|I| ≥ 2` 时 `S` 有零因子：`e_i · e_j = 0 (i ≠ j)`。因此：
///
/// - **不提供** `div` / `inv`。逐分量除法 `a / b` 在 `b_i = 0` 时未定义，
///   且不属于环公理。需要除法的地方应显式在 `K` 分量上进行并自行处理零。
/// - 不要假设 `a.mul(&b) == S::zero() ⇒ a == S::zero() ∨ b == S::zero()`。
///
/// # 工程辅助方法
///
/// 除代数公理外，本 trait 提供两个非公理方法，均服务于渲染循环中的早退优化：
///
/// - `max_abs`：分量绝对值的最大值，供调用方与阈值比较（`self.max_abs() < eps`）。
/// - `sub`：由 `add` + `neg` 导出，仅为调用便利。
///
/// 二者都**不属于**代数结构定义；移除它们不影响公理成立。
/// 特别地，`max_abs` 不构成范数：不要求三角不等式、不要求齐次性，
/// 仅要求「值可忽略」这一工程判据有依据。
///
/// `max_abs` 返回 `Self::Scalar`，比较所需的 `PartialOrd` 由调用方在
/// 泛型 bound 中自行添加（`where S::Scalar: PartialOrd`），本 trait 不强制。
/// 这样 `Scalar` 无需预先满足任何序关系即可实现本 trait。
///
/// # 与 `std::ops` 的关系
///
/// 方法可自然映射到 `std::ops`：
///
/// | 本 trait | `std::ops` |
/// |---|---|
/// | `add` | `Add<Self>` |
/// | `neg` | `Neg` |
/// | `mul` | `Mul<Self>` |
/// | `scale` | `Mul<Self::Scalar>` |
///
/// 两者不冲突，`impl` 者可以同时提供运算符重载并在其中委托到本 trait 方法，
/// 使泛型代码既能写 `a.add(&b)` 也能写 `a + b`。本 trait 不强制这一点，
/// 因为 `scale` 与 `mul` 在 `std::ops` 中共享 `Mul` 记号，需由实现者按需展开。
///
/// # 实现者义务
///
/// 1. 满足上节全部公理。违反即逻辑错误。
/// 2. `max_abs` 必须是**上界**：不得漏掉任何分量，也不得返回小于真实
///    最大绝对值的数。`f32` 的 `NaN` 行为由实现者定义并在自身文档说明。
/// 3. `Send + Sync + 'static` 属于工程约束（跨线程、泛型缓存、`Arc` 共享），
///    与代数结构无关，实现者无需额外语义。
///
/// # 方法速查
///
/// - `zero` / `one`：加法、乘法单位元
/// - `add` / `neg` / `sub`：加法群运算（`sub` 为 default 导出）
/// - `mul`：逐分量乘（Hadamard）
/// - `scale`：标量乘
/// - `max_abs`：分量绝对值最大值，工程早退用，非范数、非公理
pub trait ScalarAlgebra: Copy + Send + Sync + 'static {
    /// 标量域。`Rgb` 为 `f32`；未来可推广到 `f64` 或半精度。
    type Scalar: Copy;

    /// 加法单位元（零元）。不是乘法单位元，见 [`Self::one`]。
    fn zero() -> Self;

    /// 乘法单位元（幺元）。
    ///
    /// 物理上对应「透射率 1 / 常数谱 1」，不是「能量 1」。
    fn one() -> Self;

    /// 交换、结合。
    fn add(&self, other: &Self) -> Self;

    /// `add` 的逆。存在是因为运算承认负值。
    fn neg(&self) -> Self;

    /// 逐分量（Hadamard）乘：交换、结合、双线性。
    fn mul(&self, other: &Self) -> Self;

    /// 标量乘，与 `add` / `mul` 满足分配律。
    fn scale(&self, k: Self::Scalar) -> Self;

    /// 分量绝对值的最大值。用于早退优化：`self.max_abs() < eps`。
    ///
    /// 非范数、非公理、非代数结构的一部分。比较所需的 `PartialOrd`
    /// 由调用方在泛型 bound 中自行添加。
    fn max_abs(&self) -> Self::Scalar;

    /// 由 `add` + `neg` 导出，非公理，仅为调用便利。
    fn sub(&self, other: &Self) -> Self {
        self.add(&other.neg())
    }
}
